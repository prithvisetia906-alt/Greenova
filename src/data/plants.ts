export function getPlantById(id: string): PlantInfo | undefined {
  return plants.find(p => p.id === id);
}

export function getPlantsByKitSize(kitSize: KitSize): PlantInfo[] {
  return plants.filter(p => p.suggestedKitSize.includes(kitSize));
}

export function getPlantsByDifficulty(difficulty: PlantInfo['difficulty']): PlantInfo[] {
  return plants.filter(p => p.difficulty === difficulty);
}